#!/bin/bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/../../.." && pwd)"
cd "$PROJECT_ROOT"

export LOCAL_SSD_ROOT="${LOCAL_SSD_ROOT:-/tmp/flame-moe}"
export WANDB_PROJECT="${WANDB_PROJECT:-flame-continual-top2-qv-lora}"
export WANDB_MODE="${WANDB_MODE:-offline}"
export WANDB_LOG_CHECKPOINTS="${WANDB_LOG_CHECKPOINTS:-0}"
export TRAIN_ITERS="${TRAIN_ITERS:-1800}"
export STAGE1_REQUIRED_ITERS="${STAGE1_REQUIRED_ITERS:-1800}"
export SAVE_INTERVAL="${SAVE_INTERVAL:-600}"
export SAVE_CHECKPOINTS="${SAVE_CHECKPOINTS:-1}"
export EVAL_INTERVAL="${EVAL_INTERVAL:-$TRAIN_ITERS}"
export LOG_INTERVAL="${LOG_INTERVAL:-10}"
export TRAIN_LOG_STEP_TIME_ONLY="${TRAIN_LOG_STEP_TIME_ONLY:-0}"
export USE_GUARD="${USE_GUARD:-1}"
export MICRO_BATCH_SIZE="${MICRO_BATCH_SIZE:-72}"
export GLOBAL_BATCH_SIZE="${GLOBAL_BATCH_SIZE:-2304}"

export G2_ROOT="${G2_ROOT:-$PROJECT_ROOT/.local/weights/a100/mha/g2-checkpoints}"
export RUN_ID="${RUN_ID:-g2-exp3-top4-e8to16-ffn352-r256-wiki-to-code-routerkd-kl10p0-top4plus-allcode-newexperts-allrouter-mha-a100-bf16-mb${MICRO_BATCH_SIZE}-${TRAIN_ITERS}}"
export STAGE1_WEIGHTS_DIR="${STAGE1_WEIGHTS_DIR:-$G2_ROOT/wiki/g2-top4-e8-ffn352-r256-wiki-shared-router-qkvo-mha-a100-bf16-mb72-1800}"
export TRAIN_WEIGHTS="${TRAIN_WEIGHTS:-$G2_ROOT/code/exp3/$RUN_ID}"

export SOURCE_NUM_EXPERTS="${SOURCE_NUM_EXPERTS:-8}"
export NUM_EXPERTS="${NUM_EXPERTS:-16}"
export MOE_ROUTER_TOPK="${MOE_ROUTER_TOPK:-4}"
export MOE_FFN_HIDDEN_SIZE="${MOE_FFN_HIDDEN_SIZE:-352}"
export ATTN_LORA_RANK="${ATTN_LORA_RANK:-256}"
export ATTN_LORA_ALPHA="${ATTN_LORA_ALPHA:-$ATTN_LORA_RANK}"
export ATTN_FULL_RANK_LORA_RANK="${ATTN_FULL_RANK_LORA_RANK:-256}"
export ATTN_FULL_RANK_LORA_ALPHA="${ATTN_FULL_RANK_LORA_ALPHA:-$ATTN_FULL_RANK_LORA_RANK}"
export ATTN_FULL_RANK_LORA_TARGETS="${ATTN_FULL_RANK_LORA_TARGETS:-qkvo}"
export ATTN_FULL_RANK_LORA_ACTIVE_TARGETS="${ATTN_FULL_RANK_LORA_ACTIVE_TARGETS:-}"

# Code LM objective: all router rows and newly added Code experts train; copied Wiki experts freeze.
export SHARED_ROUTER_HYBRID_TRAIN_ALL_EXPERTS_AND_ROUTER=0
export SHARED_ROUTER_HYBRID_TRAIN_ALL_ROUTER_ROWS=1

# Experiment 3 code-step routing:
# top-k over all experts, union all newly added Code experts, original softmax weights, no renorm.
export SHARED_ROUTER_HYBRID_TOPK_WITH_ALL_NEW_EXPERTS=1
export SHARED_ROUTER_HYBRID_ALL_NEW_EXPERTS_FROM_NUM_EXPERTS="$SOURCE_NUM_EXPERTS"

# Full-Wiki teacher-student router KD, accumulated in the same optimizer step as Code LM.
export ROUTER_MEMORY_KL_COEFF="${ROUTER_MEMORY_KL_COEFF:-10.0}"
export ROUTER_MEMORY_FORCE_ENABLE_ZERO_COEFF="${ROUTER_MEMORY_FORCE_ENABLE_ZERO_COEFF:-0}"
export ROUTER_MEMORY_FRACTION="${ROUTER_MEMORY_FRACTION:-1.0}"
export ROUTER_MEMORY_INTERVAL="${ROUTER_MEMORY_INTERVAL:-1}"
export ROUTER_MEMORY_DATASET="${ROUTER_MEMORY_DATASET:-$PROJECT_ROOT/data/wiki/train}"
export ROUTER_MEMORY_EVAL_DATASET="${ROUTER_MEMORY_EVAL_DATASET:-$ROUTER_MEMORY_DATASET}"
export ROUTER_MEMORY_EVAL_INTERVAL="${ROUTER_MEMORY_EVAL_INTERVAL:-0}"
export ROUTER_MEMORY_EVAL_ITERS="${ROUTER_MEMORY_EVAL_ITERS:-1}"
export ROUTER_MEMORY_TEACHER_STUDENT_KL=1
export ROUTER_MEMORY_TEACHER_STUDENT_KL_EXISTING_EXPERTS_ONLY="${ROUTER_MEMORY_TEACHER_STUDENT_KL_EXISTING_EXPERTS_ONLY:-0}"
export ROUTER_MEMORY_JOINT_UPDATE=1
export ROUTER_KL_EARLY_STOP_ENABLED=0
export ROUTER_KL_STOP_STEP=""

# Keep the Experiment 3 objective explicit: Code LM + Wiki router KD.
export MOE_AUX_LOSS_COEFF="${MOE_AUX_LOSS_COEFF:-0.0}"
export MOE_Z_LOSS_COEFF="${MOE_Z_LOSS_COEFF:-0.0}"

export ENABLE_OLD_MODEL_KL=0
export OLD_MODEL_KL_COEFF=0.0
export OLD_MODEL_KL_TEMPERATURE=1.0
export MOE_GROUPED_GEMM="${MOE_GROUPED_GEMM:-1}"
export ATTN_LORA_GROUPED_GEMM="${ATTN_LORA_GROUPED_GEMM:-1}"
export MOE_PERMUTE_FUSION="${MOE_PERMUTE_FUSION:-0}"
export MOE_ROUTER_DTYPE="${MOE_ROUTER_DTYPE:-fp32}"

is_completed() {
    local run_dir="$1"
    local latest_file="${run_dir}/latest_checkpointed_iteration.txt"
    [ -f "$latest_file" ] && [ "$(tr -d '\n\r[:space:]' < "$latest_file")" = "$TRAIN_ITERS" ]
}

has_checkpoint_at_least() {
    local run_dir="$1"
    local required_iters="$2"
    local latest_file="${run_dir}/latest_checkpointed_iteration.txt"
    [ -f "$latest_file" ] && [ "$(tr -d '\n\r[:space:]' < "$latest_file")" -ge "$required_iters" ]
}

if ! has_checkpoint_at_least "$STAGE1_WEIGHTS_DIR" "$STAGE1_REQUIRED_ITERS"; then
    echo "[ERROR] missing completed G2 wiki checkpoint >=${STAGE1_REQUIRED_ITERS}: ${STAGE1_WEIGHTS_DIR}" >&2
    exit 1
fi

if ! compgen -G "$ROUTER_MEMORY_DATASET/*.bin" >/dev/null; then
    echo "[ERROR] full Wiki train router-memory dataset not found: $ROUTER_MEMORY_DATASET" >&2
    exit 1
fi

if is_completed "$TRAIN_WEIGHTS"; then
    echo "[SKIP] already completed: $RUN_ID"
    exit 0
fi

echo "[CONFIG] G2 Experiment 3: Wiki router KD + Code LM"
echo "[CONFIG] source wiki=${STAGE1_WEIGHTS_DIR}"
echo "[CONFIG] target code=${TRAIN_WEIGHTS}"
echo "[CONFIG] code step routing=top${MOE_ROUTER_TOPK} over all ${NUM_EXPERTS} + all code experts [${SOURCE_NUM_EXPERTS}, ${NUM_EXPERTS})"
echo "[CONFIG] routing weights=original full softmax, no renormalization"
echo "[CONFIG] trainable=all router rows + new Code FFN/attention experts"
echo "[CONFIG] frozen=copied Wiki experts + shared dense trunk"
echo "[CONFIG] KD=full Wiki teacher-student router KD, lambda=${ROUTER_MEMORY_KL_COEFF}, joint_update=${ROUTER_MEMORY_JOINT_UPDATE}"
echo "[CONFIG] aux/z loss=${MOE_AUX_LOSS_COEFF}/${MOE_Z_LOSS_COEFF}"

env \
    WANDB_MODE="$WANDB_MODE" \
    DIRECT_LOCAL_SAVE=1 \
    WANDB_LOG_CHECKPOINTS="$WANDB_LOG_CHECKPOINTS" \
    RUN_ID="$RUN_ID" \
    TRAIN_WEIGHTS="$TRAIN_WEIGHTS" \
    STAGE1_WEIGHTS_DIR="$STAGE1_WEIGHTS_DIR" \
    WANDB_PROJECT="$WANDB_PROJECT" \
    WANDB_EXP_NAME="${WANDB_EXP_NAME:-G2 - exp3 wiki router KD kl10 + top4 plus all code experts - wiki to code}" \
    RUN_INITIAL_PROBE_EVAL="${RUN_INITIAL_PROBE_EVAL:-1}" \
    RUN_INITIAL_VALID_EVAL="${RUN_INITIAL_VALID_EVAL:-1}" \
    PROBE_EVAL_INTERVAL="${PROBE_EVAL_INTERVAL:-20}" \
    SECONDARY_PROBE_EVAL_INTERVAL="${SECONDARY_PROBE_EVAL_INTERVAL:-20}" \
    MICRO_BATCH_SIZE="$MICRO_BATCH_SIZE" \
    GLOBAL_BATCH_SIZE="$GLOBAL_BATCH_SIZE" \
    TRAIN_ITERS="$TRAIN_ITERS" \
    SOURCE_REQUIRED_ITERS="$STAGE1_REQUIRED_ITERS" \
    SAVE_INTERVAL="$SAVE_INTERVAL" \
    SAVE_CHECKPOINTS="$SAVE_CHECKPOINTS" \
    EVAL_INTERVAL="$EVAL_INTERVAL" \
    LOG_INTERVAL="$LOG_INTERVAL" \
    TRAIN_LOG_STEP_TIME_ONLY="$TRAIN_LOG_STEP_TIME_ONLY" \
    SOURCE_NUM_EXPERTS="$SOURCE_NUM_EXPERTS" \
    NUM_EXPERTS="$NUM_EXPERTS" \
    MOE_ROUTER_TOPK="$MOE_ROUTER_TOPK" \
    MOE_FFN_HIDDEN_SIZE="$MOE_FFN_HIDDEN_SIZE" \
    MOE_AUX_LOSS_COEFF="$MOE_AUX_LOSS_COEFF" \
    MOE_Z_LOSS_COEFF="$MOE_Z_LOSS_COEFF" \
    ENABLE_OLD_MODEL_KL="$ENABLE_OLD_MODEL_KL" \
    OLD_MODEL_KL_COEFF="$OLD_MODEL_KL_COEFF" \
    OLD_MODEL_KL_TEMPERATURE="$OLD_MODEL_KL_TEMPERATURE" \
    ATTN_LORA_RANK="$ATTN_LORA_RANK" \
    ATTN_LORA_ALPHA="$ATTN_LORA_ALPHA" \
    ATTN_FULL_RANK_LORA_RANK="$ATTN_FULL_RANK_LORA_RANK" \
    ATTN_FULL_RANK_LORA_ALPHA="$ATTN_FULL_RANK_LORA_ALPHA" \
    ATTN_FULL_RANK_LORA_TARGETS="$ATTN_FULL_RANK_LORA_TARGETS" \
    ATTN_FULL_RANK_LORA_ACTIVE_TARGETS="$ATTN_FULL_RANK_LORA_ACTIVE_TARGETS" \
    SHARED_ROUTER_HYBRID_TRAIN_ALL_EXPERTS_AND_ROUTER="$SHARED_ROUTER_HYBRID_TRAIN_ALL_EXPERTS_AND_ROUTER" \
    SHARED_ROUTER_HYBRID_TRAIN_ALL_ROUTER_ROWS="$SHARED_ROUTER_HYBRID_TRAIN_ALL_ROUTER_ROWS" \
    SHARED_ROUTER_HYBRID_TOPK_WITH_ALL_NEW_EXPERTS="$SHARED_ROUTER_HYBRID_TOPK_WITH_ALL_NEW_EXPERTS" \
    SHARED_ROUTER_HYBRID_ALL_NEW_EXPERTS_FROM_NUM_EXPERTS="$SHARED_ROUTER_HYBRID_ALL_NEW_EXPERTS_FROM_NUM_EXPERTS" \
    ROUTER_MEMORY_KL_COEFF="$ROUTER_MEMORY_KL_COEFF" \
    ROUTER_MEMORY_FORCE_ENABLE_ZERO_COEFF="$ROUTER_MEMORY_FORCE_ENABLE_ZERO_COEFF" \
    ROUTER_MEMORY_FRACTION="$ROUTER_MEMORY_FRACTION" \
    ROUTER_MEMORY_INTERVAL="$ROUTER_MEMORY_INTERVAL" \
    ROUTER_MEMORY_DATASET="$ROUTER_MEMORY_DATASET" \
    ROUTER_MEMORY_EVAL_DATASET="$ROUTER_MEMORY_EVAL_DATASET" \
    ROUTER_MEMORY_EVAL_INTERVAL="$ROUTER_MEMORY_EVAL_INTERVAL" \
    ROUTER_MEMORY_EVAL_ITERS="$ROUTER_MEMORY_EVAL_ITERS" \
    ROUTER_MEMORY_TEACHER_STUDENT_KL="$ROUTER_MEMORY_TEACHER_STUDENT_KL" \
    ROUTER_MEMORY_TEACHER_STUDENT_KL_EXISTING_EXPERTS_ONLY="$ROUTER_MEMORY_TEACHER_STUDENT_KL_EXISTING_EXPERTS_ONLY" \
    ROUTER_MEMORY_JOINT_UPDATE="$ROUTER_MEMORY_JOINT_UPDATE" \
    ROUTER_KL_EARLY_STOP_ENABLED="$ROUTER_KL_EARLY_STOP_ENABLED" \
    ROUTER_KL_STOP_STEP="$ROUTER_KL_STOP_STEP" \
    MOE_GROUPED_GEMM="$MOE_GROUPED_GEMM" \
    ATTN_LORA_GROUPED_GEMM="$ATTN_LORA_GROUPED_GEMM" \
    MOE_PERMUTE_FUSION="$MOE_PERMUTE_FUSION" \
    MOE_ROUTER_DTYPE="$MOE_ROUTER_DTYPE" \
    MASTER_PORT="${MASTER_PORT:-29783}" \
    USE_GUARD="$USE_GUARD" \
    SCRIPT_DIR="$SCRIPT_DIR" \
    bash -lc 'if [ "$USE_GUARD" = "1" ]; then exec "$SCRIPT_DIR/run_guarded_training.sh" bash "$SCRIPT_DIR/code_from_wiki_e6_fullrank_qkvo_new_experts_all_router_mha_a100_bf16.sh"; else exec bash "$SCRIPT_DIR/code_from_wiki_e6_fullrank_qkvo_new_experts_all_router_mha_a100_bf16.sh"; fi'

echo "[DONE] G2 Experiment 3 $(date)"
